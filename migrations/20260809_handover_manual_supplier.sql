-- Передача дел: пометка «поставщика вписали руками».
--
-- Приходы в документ собираются по заказам автора (orders.created_by). У того,
-- кто заказы в портале не заводит, документ соберётся пустым, поэтому появилась
-- кнопка «+ Поставщик» — вписать карточку самому.
--
-- Без этой пометки такая карточка жила бы до первой пересборки: hoRebuildSuppliers
-- удаляет поставщиков, которых нет в заказах и у которых не заполнены примечания.
-- Человек вписал бы поставщика, нажал «Обновить приходы» — и тот бы исчез.

ALTER TABLE handover_suppliers
  ADD COLUMN is_manual TINYINT(1) NOT NULL DEFAULT 0 AFTER included;
