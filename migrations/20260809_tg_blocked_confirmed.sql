-- Телеграм: отметка «блокировка подтверждена в последний раз».
--
-- Проблема. Метку блокировки (tg_blocked_at) ставят один раз — при первом
-- отказе Telegram, и больше не трогают: UPDATE идёт с условием
-- `tg_blocked_at IS NULL`. Все проверки написаны как
-- «tg_blocked_at IS NULL OR tg_blocked_at < NOW() - INTERVAL 30 DAY»,
-- то есть через 30 дней окно открывается НАВСЕГДА и портал снова шлёт
-- каждому такому чату — каждый раз получая отказ.
--
-- Так и вышло: три чата заблокировали бота 39–59 дней назад, и за последнюю
-- неделю им ушло 56 сообщений впустую, последнее в день проверки.
--
-- Почему новая колонка, а не обновление старой: tg_blocked_at показывается
-- закупкам в «Каналах связи» и в графиках как дата, когда ресторан
-- заблокировал бота. Переписывать её на «сегодня» при каждом отказе значит
-- менять смысл того, что видит человек.
--
-- Новая колонка — служебная: только для того, чтобы не долбить в закрытую
-- дверь чаще раза в месяц.

ALTER TABLE ro_telegram_subs
  ADD COLUMN tg_blocked_confirmed_at DATETIME NULL DEFAULT NULL AFTER tg_blocked_at;

ALTER TABLE users
  ADD COLUMN tg_blocked_confirmed_at DATETIME NULL DEFAULT NULL AFTER tg_blocked_at;

-- Уже помеченным ставим СЕГОДНЯШНЮЮ дату, а не дату первой блокировки:
-- по журналу tg_send_log видно, что они блокируют бота прямо сейчас (отказы
-- приходили в день миграции). Если проставить старую дату, окно «прошло 30
-- дней» окажется уже открытым и каждому уйдёт ещё одна порция в никуда.
UPDATE ro_telegram_subs SET tg_blocked_confirmed_at = NOW() WHERE tg_blocked_at IS NOT NULL;
UPDATE users            SET tg_blocked_confirmed_at = NOW() WHERE tg_blocked_at IS NOT NULL;
