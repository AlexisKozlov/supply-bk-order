-- Индекс по дате подачи заявки.
--
-- На главной у сотрудника появилась строка «N заявок на сегодня» — она
-- считается запросом по so_orders.order_date. Индексов по этой колонке не
-- было (все существующие — по delivery_date), и запрос читал таблицу
-- целиком: EXPLAIN показывал type=ALL, 2492 строки.
--
-- Сейчас это 4 мс и никого не беспокоит, но таблица растёт линейно:
-- рестораны × поставщики × даты. Через год это десятки тысяч строк на
-- каждом открытии главной.
--
-- Колонки в порядке использования в запросе: сначала точное совпадение по
-- дате, потом фильтр по юрлицу, потом статус (по нему считается SUM).

CREATE INDEX idx_so_orders_order_date
  ON so_orders (order_date, legal_entity, status);
