--
-- Проблема. В админке на вкладке «Сотрудники» под каждым человеком пишется
-- «был N дней назад». Бралось это из журнала входов login_log — то есть из
-- последнего входа ПО ПАРОЛЮ. Сессия живёт неделями, поэтому человек,
-- который прямо сейчас работает в портале, показывался как «был 10 дней
-- назад», а через 60 дней ещё и краснел как «давно не заходил».
--
-- Правильные данные лежат в user_presence.last_seen — её обновляет heartbeat
-- каждые несколько секунд. Но JOIN с users не работал: user_presence в
-- utf8mb4_general_ci, а users.name в utf8mb4_unicode_ci, и MariaDB отвечает
-- «Illegal mix of collations». В коде этого никто не видел, потому что
-- запрос с JOIN просто не писали.
--
-- Приводим таблицу к той же сортировке, что и users. Таблица маленькая
-- (одна строка на сотрудника), простоя не будет.

ALTER TABLE user_presence
  CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
