-- Заявки поставщикам: возможность полностью отключить товар шаблона для заказа.
-- Флаг переживает пересохранение шаблона (в отличие от служебного is_active,
-- который гасится и пересоздаётся при каждом сохранении). order_disabled = 1 →
-- товар полностью скрыт из формы заказа ресторана и из бота, подать по нему
-- количество нельзя. В шаблоне у закупщика товар остаётся — чтобы включить обратно.
ALTER TABLE so_templates
  ADD COLUMN order_disabled TINYINT(1) NOT NULL DEFAULT 0 AFTER is_active;
