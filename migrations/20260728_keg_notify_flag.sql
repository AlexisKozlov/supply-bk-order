-- Отдельный переключатель уведомлений по возврату кег.
--
-- Раньше сообщения о кегах (маршрутизация, ТТН, напоминание о вывозе) уходили
-- ВСЕМ привязанным сотрудникам ресторана без возможности отключить: флага для
-- них не было, в отличие от заявок поставщикам и сбора остатков.
--
-- Включён по умолчанию: поведение не меняется, но теперь можно отключить
-- точечно в разделе «Telegram-бот».

ALTER TABLE ro_telegram_subs
    ADD COLUMN notify_keg_returns TINYINT(1) NOT NULL DEFAULT 1 AFTER notify_stock_sessions;

-- Существующим подписчикам включаем явно (на случай, если DEFAULT не применился).
UPDATE ro_telegram_subs SET notify_keg_returns = 1;
