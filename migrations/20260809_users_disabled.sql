-- Отключение учётных записей, которыми не пользуются.
--
-- Зачем: доступ к порталу остаётся у людей, которые давно не заходят —
-- перешли в другой отдел, уволились, завели «на всякий случай». Проверить
-- это было нечем, пока не заработал журнал входов (миграция
-- 20260809_login_log_collation).
--
-- Колонки, а не удаление записи: у пользователя есть история действий в
-- audit_log, задачи, заявки. Удалять его нельзя, надо просто закрыть вход.
--
-- disabled_at пустой = доступ есть. Заполнен = вход закрыт, в админке видно
-- когда и почему. Снять отключение — обнулить обе колонки (кнопка в админке).

ALTER TABLE users
  ADD COLUMN disabled_at DATETIME NULL DEFAULT NULL,
  ADD COLUMN disabled_reason VARCHAR(255) NULL DEFAULT NULL;

CREATE INDEX idx_users_disabled_at ON users (disabled_at);
