-- Привязка сотрудника портала к «своим» поставщикам.
--
-- Нужно для внешних пользователей: сотрудники производственного центра
-- (ПРЦ) заходят в модуль «Заявки поставщикам», чтобы видеть заявки на
-- тесто. Без ограничения им видны заявки ко всем поставщикам юрлица —
-- то есть чужие объёмы закупок.
--
-- Пусто / NULL — ограничения нет (обычные закупщики видят всех).
-- Иначе — JSON-массив suppliers.id, доступных пользователю в модуле.
-- Администраторов ограничение не касается.

ALTER TABLE users
  ADD COLUMN supplier_scope TEXT NULL DEFAULT NULL AFTER legal_entities;
