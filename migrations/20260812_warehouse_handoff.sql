-- Поставка через склад: поставщик привозит на склад, ресторан получает позже,
-- с ближайшей основной поставкой. Ресторану надо показывать ЕГО дату, а
-- поставщику — складскую (её же считает дедлайн и по ней собираются документы).

-- Галочка на строке графика: этот ресторан снабжается через склад.
ALTER TABLE supplier_schedules
  ADD COLUMN via_warehouse TINYINT(1) NOT NULL DEFAULT 0
      COMMENT 'Поставщик везёт на склад, ресторан получает с основной поставкой'
  AFTER delivery_day;

-- Фактическая дата получения рестораном. NULL = совпадает с delivery_date
-- (обычная прямая поставка).
ALTER TABLE so_orders
  ADD COLUMN restaurant_delivery_date DATE NULL
      COMMENT 'Когда ресторан реально получит товар (при поставке через склад)'
  AFTER delivery_date;
